#!/usr/bin/env python3
"""Writes the wild encounter sections of docs/WALKTHROUGH.md from Pink's source.

Usage: gen_walkthrough_encounters.py <pokepink_root> [walkthrough.md ...]

Reads data/wild/maps/*.asm (grass and surfing), good_rod.asm and
super_rod.asm, and replaces everything between the encounter markers in each
walkthrough with one checklist line per map, in story order. A line gives each
species' share of encounters there and its levels, from the slot odds in
data/wild/probabilities.asm (20, 20, 15, 10, 10, 10, 5, 5, 4 and 1 percent)
and the Super Rod's in engine/items/super_rod.asm (40, 30, 20, 10).
"""
import os, re, sys

pink = sys.argv[1]
docs = sys.argv[2:] or [os.path.join(os.path.dirname(__file__), "..", "docs", "WALKTHROUGH.md")]

SLOTS = [51, 51, 39, 25, 25, 25, 13, 13, 11, 3]
SUPER = [102, 76, 51, 27]
START, END = "<!-- encounters: generated by tools/gen_walkthrough_encounters.py -->", "<!-- /encounters -->"

NAMES = {"NIDORAN_F": "Nidoran♀", "NIDORAN_M": "Nidoran♂", "MR_MIME": "Mr. Mime", "FARFETCHD": "Farfetch'd"}


def species(const):
    return NAMES.get(const, const.capitalize())


def place(stem):
    s = re.sub(r"^Route(\d+)$", r"Route \1", stem)
    s = s.replace("MtMoon", "Mt. Moon ").replace("RockTunnel", "Rock Tunnel ")
    s = s.replace("PokemonTower", "Pokémon Tower ").replace("PokemonMansion", "Pokémon Mansion ")
    s = s.replace("SeafoamIslands", "Seafoam Islands ").replace("VictoryRoad", "Victory Road ")
    s = s.replace("CeruleanCave", "Cerulean Cave ").replace("SafariZone", "Safari Zone ")
    s = s.replace("ViridianForest", "Viridian Forest").replace("DiglettsCave", "Diglett's Cave")
    s = s.replace("PowerPlant", "Power Plant")
    return s.strip()


def read_map(stem):
    text = open(os.path.join(pink, "data/wild/maps", stem + ".asm"), encoding="utf-8").read()
    out = {}
    for kind in ("grass", "water"):
        m = re.search(r"def_%s_wildmons\s+(\d+)(.*?)end_%s_wildmons" % (kind, kind), text, re.S)
        if not m or int(m.group(1)) == 0:
            continue
        slots = []
        for line in m.group(2).split("\n"):
            line = line.split(";")[0]
            e = re.match(r"\s*db\s+(\d+)\s*,\s*([A-Z_0-9]+)", line)
            if e:
                slots.append((int(e.group(1)), e.group(2)))
        out[kind] = slots
    return out


def summary(slots, odds):
    total = sum(odds)
    by = {}
    for (level, mon), chance in zip(slots, odds):
        share, lo, hi = by.get(mon, (0, level, level))
        by[mon] = (share + chance, min(lo, level), max(hi, level))
    parts = []
    for mon, (share, lo, hi) in sorted(by.items(), key=lambda kv: -kv[1][0]):
        pct = share * 100 / total
        pct = ("%d%%" % round(pct)) if pct >= 1 else "1%"
        levels = ("L%d" % lo) if lo == hi else ("L%d-%d" % (lo, hi))
        parts.append("%s %s %s" % (species(mon), pct, levels))
    return ", ".join(parts)


AREAS = [
    ("Wild Pokémon: Route 1 to Mt. Moon", ["Route1", "Route22", "Route2", "ViridianForest", "Route3",
                                            "MtMoon1F", "MtMoonB1F", "MtMoonB2F", "Route4"]),
    ("Wild Pokémon: Cerulean to Vermilion", ["Route24", "Route25", "Route5", "Route6", "Route11", "DiglettsCave"]),
    ("Wild Pokémon: Rock Tunnel to Lavender", ["Route9", "Route10", "RockTunnel1F", "RockTunnelB1F", "PowerPlant",
                                               "Route8", "Route7", "PokemonTower3F", "PokemonTower4F",
                                               "PokemonTower5F", "PokemonTower6F", "PokemonTower7F"]),
    ("Wild Pokémon: Routes 12 to 18 and the Safari Zone", ["Route12", "Route13", "Route14", "Route15", "Route16",
                                                           "Route17", "Route18", "SafariZoneCenter",
                                                           "SafariZoneEast", "SafariZoneNorth", "SafariZoneWest"]),
    ("Wild Pokémon: the sea routes, Seafoam and Cinnabar", ["Route19", "Route20", "Route21", "SeafoamIslands1F",
                                                            "SeafoamIslandsB1F", "SeafoamIslandsB2F",
                                                            "SeafoamIslandsB3F", "SeafoamIslandsB4F",
                                                            "PokemonMansion1F", "PokemonMansion2F",
                                                            "PokemonMansion3F", "PokemonMansionB1F"]),
    ("Wild Pokémon: Victory Road and Cerulean Cave", ["Route23", "VictoryRoad1F", "VictoryRoad2F", "VictoryRoad3F",
                                                      "CeruleanCave1F", "CeruleanCave2F", "CeruleanCaveB1F"]),
]

lines = [START, ""]
covered = set()
for title, stems in AREAS:
    lines.append("## " + title)
    lines.append("")
    if title.endswith("Mt. Moon"):
        lines.append("Each line gives a species' share of encounters there and its levels. "
                     "**Expected:** Zubat turns up outside caves in Pink, on Routes 3, 4 and 22 "
                     "and in Viridian Forest, as it does in the manga.")
        lines.append("")
    for stem in stems:
        covered.add(stem)
        data = read_map(stem)
        if "grass" in data:
            where = "grass" if stem.startswith("Route") or stem.startswith("Safari") or stem == "ViridianForest" else "walking"
            lines.append("- [ ] %s (%s): %s" % (place(stem), where, summary(data["grass"], SLOTS)))
        if "water" in data:
            lines.append("- [ ] %s (surfing): %s" % (place(stem), summary(data["water"], SLOTS)))
    lines.append("")

missing = sorted(set(f[:-4] for f in os.listdir(os.path.join(pink, "data/wild/maps")))
                 - covered - {"nothing", "PokemonTower1F", "PokemonTower2F"})
if missing:
    raise SystemExit("maps left out of AREAS: " + ", ".join(missing))

# fishing
lines.append("## Wild Pokémon: fishing")
lines.append("")
lines.append("- [ ] Old Rod, anywhere with water: Magikarp L5.")
good = re.findall(r"db\s+(\d+)\s*,\s*([A-Z_]+)", open(os.path.join(pink, "data/wild/good_rod.asm")).read())
lines.append("- [ ] Good Rod, anywhere with water: " + ", ".join(
    "%s 50%% L%s" % (species(m), lv) for lv, m in good) + ".")
super_text = open(os.path.join(pink, "data/wild/super_rod.asm")).read()
for row in re.findall(r"db\s+([A-Z_0-9]+),\s*(.+)", super_text):
    mapname, rest = row
    vals = [v.strip() for v in rest.split(";")[0].split(",")]
    slots = [(int(vals[i + 1]), vals[i]) for i in range(0, 8, 2)]
    name = " ".join(w.capitalize() for w in mapname.split("_"))
    name = (name.replace("Route ", "Route ").replace("Safari Zone ", "Safari Zone ")
            .replace("Seafoam Islands ", "Seafoam Islands ").replace("Cerulean Cave ", "Cerulean Cave "))
    name = re.sub(r"\b(B?\d+f)\b", lambda m: m.group(1).upper(), name)
    lines.append("- [ ] Super Rod, %s: %s" % (name, summary(slots, SUPER)))
lines.append("")
lines.append(END)
block = "\n".join(lines)

for path in docs:
    text = open(path, encoding="utf-8").read()
    if START in text:
        text = text[:text.index(START)] + block + text[text.index(END) + len(END):]
    else:
        anchor = "## Wild Pokémon, all game"
        text = text.replace(anchor, block + "\n\n" + anchor, 1)
    open(path, "w", encoding="utf-8").write(text)
    print("wrote encounters into %s" % path)
