#!/usr/bin/env python3
"""Generate pink_tilesets/tile_data.lua and assets/pink_tiles.png.

Usage: gen_tile_data.py <pokepink_root> <pokeyellow_root> <install_root> <mod_dir>

<install_root> is a Gen1Recomp save folder with Red, Blue and Yellow imported
(<install_root>/<game>/assets/generated/tilesets/*.png). It is only read here,
to learn WHERE each changed tile can be found; no imported pixels are written.

For every tile Pink changes in a tileset sheet:
  - if the same tile exists in the player's Red or Blue import, record its
    position (game, sheet, index). The mod copies it from the player's own
    import at runtime, so the tile itself never ships.
  - otherwise the tile is Pink's own (in no Red, Blue or Yellow cart) and is
    packed into assets/pink_tiles.png, credited to jcferggy.
"""
import os, re, sys
from PIL import Image

pink, yellow, install, mod_dir = sys.argv[1:5]
SHEETS = ["overworld", "forest", "facility", "gate", "gym", "lab", "mansion", "plateau",
          "ship_port", "cavern", "cemetery", "club", "house", "interior", "lobby",
          "pokecenter", "reds_house", "ship", "underground"]


def tiles(path):
    im = Image.open(path).convert("L")
    w, h = im.size
    return [bytes(min(3, round(v / 85)) for v in im.crop((x, y, x + 8, y + 8)).tobytes())
            for y in range(0, h, 8) for x in range(0, w, 8)]


# where each tile exists in the player's Red/Blue imports (Red first)
sources = {}
for game in ("red", "blue"):
    for sheet in SHEETS:
        p = os.path.join(install, game, "assets/generated/tilesets", sheet + ".png")
        if not os.path.exists(p):
            continue
        for i, t in enumerate(tiles(p)):
            sources.setdefault(t, (game, sheet, i))

borrow, own_tiles, own_index = {}, [], {}
for sheet in SHEETS:
    pp = os.path.join(pink, "gfx/tilesets", sheet + ".png")
    yp = os.path.join(yellow, "gfx/tilesets", sheet + ".png")
    if not (os.path.exists(pp) and os.path.exists(yp)):
        continue
    a, b = tiles(yp), tiles(pp)
    for i in range(min(len(a), len(b))):
        if a[i] == b[i]:
            continue
        src = sources.get(b[i])
        if src:
            borrow.setdefault(sheet, {})[i] = src
        else:
            if b[i] not in own_index:
                own_index[b[i]] = len(own_tiles)
                own_tiles.append(b[i])
            borrow.setdefault(sheet, {})[i] = ("pink", own_index[b[i]])

# Pink's own tiles: one 8px-tall row per tile, 16 per row, the importer's greys
cols = 16
rows = (len(own_tiles) + cols - 1) // cols
img = Image.new("L", (cols * 8, max(1, rows) * 8), 255)
for n, t in enumerate(own_tiles):
    tile = Image.frombytes("L", (8, 8), bytes(v * 85 for v in t))  # 0..3 -> 0, 85, 170, 255
    img.paste(tile, ((n % cols) * 8, (n // cols) * 8))
os.makedirs(os.path.join(mod_dir, "assets"), exist_ok=True)
img.save(os.path.join(mod_dir, "assets", "pink_tiles.png"))


def lua(v, ind=0):
    pad = "  " * ind
    if isinstance(v, dict):
        items = []
        for k in sorted(v, key=lambda x: (isinstance(x, str), x)):
            key = "[%d]" % k if isinstance(k, int) else (k if re.match(r"^[A-Za-z_]\w*$", k) else '["%s"]' % k)
            items.append("%s  %s = %s," % (pad, key, lua(v[k], ind + 1)))
        return "{\n" + "\n".join(items) + "\n" + pad + "}" if items else "{}"
    if isinstance(v, tuple):
        if v[0] == "pink":
            return '{ pink = %d }' % v[1]
        return '{ game = "%s", sheet = "%s", tile = %d }' % v
    return repr(v)


# tile indexes are 0-based, matching the engine's tile ids
with open(os.path.join(mod_dir, "tile_data.lua"), "w") as f:
    f.write("-- generated by gen_tile_data.py; do not edit.\n")
    f.write("-- sheet -> { [tile index] = { game, sheet, tile } (copied from the player's own\n")
    f.write("-- Red/Blue import at runtime) or { pink = n } (assets/pink_tiles.png, jcferggy's art) }\n")
    f.write("return " + lua(borrow) + "\n")

n_borrow = sum(1 for s in borrow.values() for v in s.values() if v[0] != "pink")
n_pink = sum(1 for s in borrow.values() for v in s.values() if v[0] == "pink")
print("sheets:", {k: len(v) for k, v in borrow.items()})
print("borrowed from the player's Red/Blue:", n_borrow, "| Pink's own:", n_pink,
      "(%d unique, packed into pink_tiles.png)" % len(own_tiles))
