#!/usr/bin/env python3
"""Generate pink_world_tweaks/text_data.lua: Pink's rewritten lines.

Usage: gen_text_data.py <pokepink_root> <pokeyellow_base_root> <out.lua>

<pokeyellow_base_root> is the pret pokeyellow checkout Pink was built on
(commit 3d300551, 2026-06-07: the closest by diff to Pink's tree), so the
comparison sees Pink's changes and not later pret clean-ups.

Writes every text label whose words Pink changed, or added, that no other
mod in this repo already carries (a label another mod's Lua names is left to
that mod).  Labels Pink added for its own new scripts are only useful with
those scripts; the ones another mod ports under its own name are skipped
via COVERED_ELSEWHERE.
"""
import glob, os, re, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from pret_text import load_labels

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OWN = "pink_world_tweaks"

# Pink labels another mod ports under a name of its own
COVERED_ELSEWHERE = {
    "_VermilionReturningChap": "pink_world_tweaks _PinkVermilionReturningChapText",
    "_VermilionDockUnusedText": "pink_world_tweaks _PinkVermilionDockSignText",
}


def lua_str(v):
    return '"' + v.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") \
                  .replace("\f", "\\f").replace("\x0b", "\\v") + '"'


def main():
    pink, base, out_path = sys.argv[1], sys.argv[2], sys.argv[3]
    P, Y = load_labels(pink), load_labels(base)
    covered = set()
    for f in glob.glob(os.path.join(HERE, "mods", "*", "*.lua")):
        # this mod's own scripts use the labels this file provides
        if os.path.basename(os.path.dirname(f)) == OWN and os.path.basename(f) != "world_data.lua":
            continue
        covered |= set(re.findall(r"(_[A-Za-z0-9_]+)", open(f, encoding="utf-8").read()))
    lines, skipped = {}, []
    for k, v in sorted(P.items()):
        if k in Y and Y[k] == v:
            continue
        if k in COVERED_ELSEWHERE or k in covered:
            skipped.append(k)
            continue
        lines[k] = v
    with open(out_path, "w", encoding="utf-8") as f:
        f.write("-- generated by gen_text_data.py from Pokemon Pink's text/*.asm; do not edit.\n")
        f.write("-- Text is Pokemon Pink's, by jcferggy.\n")
        f.write("-- label -> line, for every label Pink rewrote or added that no other mod carries.\n")
        f.write("return {\n")
        for k in sorted(lines):
            f.write("  %s = %s,\n" % (k, lua_str(lines[k])))
        f.write("}\n")
    print("lines:", len(lines), "| left to other mods:", len(skipped))


if __name__ == "__main__":
    main()
